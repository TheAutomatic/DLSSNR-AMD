// `gfx11_mach` (an EF_AMDGPU_MACH of gfx11, RDNA3's records): the ELF says that machine and the prefix is gfx11's;
// 0: RDNA4's template as it is.
inline bool build_model_elf_from_nrp(const uint8_t* nrp, size_t nrp_bytes, const uint32_t spv_dims[3],
                                     Bytes* out_elf, uint32_t out_dims[3], std::string* why, uint32_t gfx11_mach = 0) {
    try {
        NrRecord rec = parse_nrpal001(nrp, nrp_bytes);
        if (spv_dims && spv_dims[0] && spv_dims[0] * spv_dims[1] * spv_dims[2] == rec.wg) {
            rec.dims[0] = spv_dims[0];
            rec.dims[1] = spv_dims[1];
            rec.dims[2] = spv_dims[2];
        } else if (rec.tidig() == 0) {
            rec.dims[0] = rec.wg;
            rec.dims[1] = 1;
            rec.dims[2] = 1;
        } else {
            rec.dims[0] = 8;
            rec.dims[1] = 8;
            rec.dims[2] = 1;
        }
        ElfView e = parse_elf(kCarrierTemplateElf, sizeof kCarrierTemplateElf);
        ElfView::Sec* text = find_sec(e, ".text");
        ElfView::Sec* note = find_sec(e, ".note");
        require(text && note, "carrier ELF is missing .text or .note");
        require(retarget_metadata(note->data, rec), "carrier note is not AMDGPU metadata");
        uint32_t ns = rd_u32(note->data.data());
        uint32_t ds = rd_u32(note->data.data() + 4);
        size_t desc = 12 + ((size_t(ns) + 3) & ~size_t(3));
        size_t p = 0;
        Mp root = mp_decode(note->data.data() + desc, ds, p);
        require(p == ds, "retargeted note did not round-trip");
        Mp& cs = mp_need(mp_need(mp_need(root, "amdpal.pipelines").items[0], ".hardware_stages"), ".cs");
        UavSgpr uav = find_uav_sgpr(mp_need(cs, ".user_data_reg_map"));
        Bytes prefix = build_prefix(rec, uav, gfx11_mach != 0);
        text->data = std::move(prefix);
        text->data.insert(text->data.end(), rec.code.begin(), rec.code.end());
        patch_symbol_size(e, text->data.size() - (rec.code.size() - rec.exec));
        *out_elf = link_elf(e);
        if (gfx11_mach) (*out_elf)[48] = uint8_t(gfx11_mach);   // e_flags' machine byte: the gfx11 machine (the feature bits kept)
        out_dims[0] = rec.dims[0];
        out_dims[1] = rec.dims[1];
        out_dims[2] = rec.dims[2];
        return true;
    } catch (const std::exception& x) {
        *why = x.what();
        return false;
    }
}


// The root signature of an ACO kernel's pipeline: `constants` root constants (the kernel's user SGPRs: the network's
// one, the table's address; the canary's eleven) and one root UAV, as the carrier template's user data map has them.
inline bool create_carrier_root_signature(ID3D12Device* device, uint32_t constants, ID3D12RootSignature** out_rs,
                                          std::string* why) {
    *out_rs = nullptr;
    D3D12_ROOT_PARAMETER params[2]{};
    params[0].ParameterType = D3D12_ROOT_PARAMETER_TYPE_32BIT_CONSTANTS;
    params[0].ShaderVisibility = D3D12_SHADER_VISIBILITY_ALL;
    params[0].Constants.ShaderRegister = 0;
    params[0].Constants.RegisterSpace = 0;
    params[0].Constants.Num32BitValues = constants;
    params[1].ParameterType = D3D12_ROOT_PARAMETER_TYPE_UAV;
    params[1].ShaderVisibility = D3D12_SHADER_VISIBILITY_ALL;
    params[1].Descriptor.ShaderRegister = 0;
    params[1].Descriptor.RegisterSpace = 0;
    D3D12_ROOT_SIGNATURE_DESC desc{};
    desc.NumParameters = 2;
    desc.pParameters = params;
    desc.Flags = D3D12_ROOT_SIGNATURE_FLAG_NONE;
    ID3DBlob *sig = nullptr, *err = nullptr;
    HRESULT hr = D3D12SerializeRootSignature(&desc, D3D_ROOT_SIGNATURE_VERSION_1_0, &sig, &err);
    if (err) err->Release();
    if (FAILED(hr) || !sig) { *why = "D3D12SerializeRootSignature " + hr_hex(hr); return false; }
    hr = device->CreateRootSignature(0, sig->GetBufferPointer(), sig->GetBufferSize(), IID_PPV_ARGS(out_rs));
    sig->Release();
    if (FAILED(hr) || !*out_rs) { *why = "CreateRootSignature " + hr_hex(hr); return false; }
    return true;
}

inline bool read_file_w(const std::wstring& path, Bytes* out) {
    FILE* f = _wfopen(path.c_str(), L"rb");
    if (!f) return false;
    std::fseek(f, 0, SEEK_END);
    const long n = std::ftell(f);
    std::fseek(f, 0, SEEK_SET);
    out->resize(n > 0 ? size_t(n) : 0);
    const bool ok = n > 0 && std::fread(out->data(), 1, out->size(), f) == out->size();
    std::fclose(f);
    return ok;
}

inline std::wstring utf8_to_wide(const std::string& s) {
    if (s.empty()) return {};
    const int n = MultiByteToWideChar(CP_UTF8, 0, s.c_str(), int(s.size()), nullptr, 0);
    std::wstring w(size_t(n > 0 ? n : 0), L'\0');
    if (n > 0) MultiByteToWideChar(CP_UTF8, 0, s.c_str(), int(s.size()), w.data(), n);
    return w;
}

// The record an RDNA3 stand-in names: OpModuleProcessed "nr-aco-record <16 hex digits>" (nr_pipeline_binary.hpp's
// record_reference, the same parse); 0: none (the SPIR-V is the network's own, its FNV names its record).
inline uint64_t record_reference(const Bytes& spv) {
    static const char tag[] = "nr-aco-record ";
    const size_t words = spv.size() / 4;
    const auto at = [&](size_t i) { uint32_t v = 0; std::memcpy(&v, spv.data() + 4 * i, 4); return v; };
    for (size_t p = 5; p < words;) {
        const uint32_t n = at(p) >> 16, op = at(p) & 65535u;
        if (!n || n > words - p) return 0;
        if (op == 330 && n >= 2) {   // OpModuleProcessed
            const char* t = reinterpret_cast<const char*>(spv.data() + 4 * (p + 1));
            const size_t len = strnlen(t, (n - 1) * 4);
            if (len == sizeof tag - 1 + 16 && std::memcmp(t, tag, sizeof tag - 1) == 0) {
                uint64_t h = 0;
                for (size_t i = sizeof tag - 1; i < len; ++i) {
                    const char c = t[i];
                    const int d = c >= '0' && c <= '9' ? c - '0' : c >= 'a' && c <= 'f' ? c - 'a' + 10 : -1;
                    if (d < 0) return 0;
                    h = (h << 4) | uint64_t(d);
                }
                return h;
            }
        }
        if (op == 54) break;   // OpFunction: past the debug section
        p += n;
    }
    return 0;
}

// A kernel's ELF from its record: <aco>\records\<FNV of its SPIR-V>.nrp, or <aco>\int4\records\ for the int4 layers'
// SPIR-V (a folder of int4 SPIR-V). `aco` is the package's dlssnr-amd\aco (d3d12_passthrough::aco_folder()). RDNA3
// (`gfx11_mach`
// not 0): the records in <aco>\rdna3\records (int4: <aco>\rdna3\int4\records), named by the stand-in's reference.
inline bool load_kernel_elf(const std::string& spv_dir, const std::wstring& aco_in, const Bytes& spv,
                            Bytes* out_elf, uint32_t out_dims[3], std::string* out_stem, std::string* why,
                            uint32_t gfx11_mach = 0) {
    const std::wstring aco = gfx11_mach ? aco_in + L"\\rdna3" : aco_in;
    const uint64_t ref = gfx11_mach ? record_reference(spv) : 0;
    char stem[32];
    std::snprintf(stem, sizeof stem, "%016llx", (unsigned long long)(ref ? ref : fnv_hash(spv.data(), spv.size())));
    if (out_stem) *out_stem = stem;
    const std::wstring file = utf8_to_wide(std::string(stem) + ".nrp");
    // The int4 layers' SPIR-V sits in <data>\int4\shaders, int4-performance\shaders, int4-ultra\shaders (RDNA3:
    // aco\rdna3\<the same>\shaders): the folder above `shaders`, not a substring anywhere in the path - a game
    // installed under "...\Sprint4\..." is not one.
    const bool want_int4 = [&] {
        std::string d = spv_dir;
        while (!d.empty() && (d.back() == '\\' || d.back() == '/')) d.pop_back();
        auto last = [&](std::string& path) {
            const size_t cut = path.find_last_of("\\/");
            std::string name = cut == std::string::npos ? path : path.substr(cut + 1);
            path = cut == std::string::npos ? std::string() : path.substr(0, cut);
            return name;
        };
        std::string name = last(d);
        if (name == "shaders") name = last(d);
        return name.rfind("int4", 0) == 0;
    }();
    Bytes nrp;
    if (!read_file_w(aco + (want_int4 ? L"\\int4\\records\\" : L"\\records\\") + file, &nrp)) {
        *why = std::string("no ACO record ") + stem + ".nrp in dlssnr-amd\\aco" + (gfx11_mach ? "\\rdna3" : "") +
               (want_int4 ? "\\int4" : "") + "\\records";
        return false;
    }
    uint32_t spv_dims[3] = {0, 0, 0};
    spv_local_size(spv.data(), spv.size(), spv_dims);
    return build_model_elf_from_nrp(nrp.data(), nrp.size(), spv_dims, out_elf, out_dims, why, gfx11_mach);
}

